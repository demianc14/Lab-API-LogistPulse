-- Esquema base: el mismo que generaba Hibernate con ddl-auto=update (SQL portable H2 + PostgreSQL).

create table warehouse (
    id      bigint generated by default as identity primary key,
    name    varchar(255) not null,
    originx integer      not null,
    originy integer      not null,
    constraint uk_warehouse_name unique (name)
);

create table robot (
    id           bigint generated by default as identity primary key,
    code         varchar(20) not null,
    battery      integer     not null,
    status       varchar(10) not null,
    version      bigint      not null,
    x            integer     not null,
    y            integer     not null,
    warehouse_id bigint      not null,
    constraint uk_robot_code unique (code),
    constraint fk_robot_warehouse foreign key (warehouse_id) references warehouse (id),
    constraint robot_status_check check (status in ('IDLE', 'BUSY'))
);

create table orders (
    id            bigint generated by default as identity primary key,
    code          varchar(20)  not null,
    customer_name varchar(80)  not null,
    destx         integer      not null,
    desty         integer      not null,
    status        varchar(20)  not null,
    eta_minutes   integer,
    created_at    timestamp(6) with time zone not null,
    version       bigint       not null,
    robot_id      bigint,
    warehouse_id  bigint       not null,
    constraint uk_orders_code unique (code),
    constraint fk_orders_robot foreign key (robot_id) references robot (id),
    constraint fk_orders_warehouse foreign key (warehouse_id) references warehouse (id),
    constraint orders_status_check check
        (status in ('CREATED', 'DISPATCHED', 'IN_TRANSIT', 'DELIVERED', 'CANCELLED', 'RETURNED'))
);

create index idx_orders_status on orders (status);

create table outbox_event (
    id         bigint generated by default as identity primary key,
    type       varchar(40)  not null,
    payload    varchar(200) not null,
    created_at timestamp(6) with time zone not null,
    sent_at    timestamp(6) with time zone
);
